"""Copy the small result files behind the ledger (docs/RESULTS.md, E21 onward) from the run store into
`results/`, with a manifest of sources and checksums, so the numbers can be recomputed from git alone.

Collected: per-family discovery tables (`bench.jsonl`), bootstrap summaries (`summary.json`), proposer RL reward logs
(`steps.jsonl`), consensus and E39 analysis rows, held-out comparison logs and calibration notes. Not collected:
candidate code and per-input model outputs (`candidates.jsonl`, `*.out.json`), traces, adapters and weights; those
stay in the run store (paths in the manifest's `source`).
"""

from __future__ import annotations

import hashlib
import json
import shutil
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
RUNS = Path("/project/alex_phd/runs/selective-recursion-20261019")
HOME = Path("/home/atowell/research-runs/selective-recursion-20261019")
README = """# Result data behind ledger rows E21 onward

Generated by `../collect_results.py` from the run store; do not edit by hand (rerun the script). `MANIFEST.json`
lists every file with its source path in the run store, size and SHA-256.

| Folder | What | Ledger rows |
| --- | --- | --- |
| `discovery/` | One row per family per discovery run (`bench.jsonl`): success at teaching mean 0.9, best score, candidates to success, proposer output tokens. Run names give proposer and seed (`-r2` = boot seed 1). | E26 to E26g, E36 to E42, E39 |
| `bootstrap/` | One summary per bootstrap run (`summary.json`): best teaching mean, round and candidate of the best, acceptance, shown examples. MRCR (`e21-boot-*`), OOLONG (`e35*-boot-*`). | E21, E35, E35b, E35c |
| `rl/` | Proposer RL logs, one row per step: families, rewards per sample, loss, adapter name. | E26c, E26g, E36, E41, E42, E43 |
| `analyses/e37-consensus/` | Per family: valid candidates, largest agreement group, oracle, exact/MBR/cross acceptance and correctness (`consensus_analysis.py`). | E37 |
| `analyses/e39*-analysis/` | The pre-registered E39 analysis, its replication (`e39r`), arm C (`e39c`) and the checkpoint-robustness runs (`e39a-<checkpoint>`), from `e39_analysis.py`: per family acceptance, fresh-task score and tokens per arm; `analysis*.log` hold the summary lines. | E39 |
| `analyses/e49-noisy-labels/` | Held-out scores of all 30 OOLONG counting candidates and the label curve (`e49_analysis.py`). | E49 |
| `analyses/e35c-heldout-*` | Held-out OOLONG counting comparison of bootstrapped and shipped libraries (`e35c_heldout.py`). | E35c |
| `calibration/` | Scores of the shipped OOLONG library on the bootstrap teaching sets (the match bars). | E35, E35c |

Not included: candidate code and per-input outputs (`candidates.jsonl`, `*.out.json`), traces, adapters and model
weights, which stay in the run store (`/project/alex_phd/runs/selective-recursion-20261019`).
"""


def sources() -> list[tuple[Path, str]]:
    out = [(f, f"discovery/{f.parent.name}.bench.jsonl") for f in sorted(RUNS.glob("*/bench.jsonl"))]
    out += [(f, f"bootstrap/{f.parent.name}.summary.json") for f in sorted(RUNS.glob("e*-boot-*/summary.json"))]
    out += [(f, f"rl/{f.parent.name}.steps.jsonl") for f in sorted(HOME.glob("e*proposer-rl*/steps.jsonl"))
            + sorted(HOME.glob("e4*-rl-*/steps.jsonl"))]
    out += [(f, f"analyses/e37-consensus/{f.parent.name}.consensus.jsonl") for f in sorted(RUNS.glob("e37*/consensus.jsonl"))]
    for d in sorted(x.name for x in HOME.glob("e39*-analysis")) + sorted(x.name for x in HOME.glob("e51*-analysis")) + sorted(x.name for x in HOME.glob("e53*-analysis")):
        out += [(HOME / d / "e39_rows.jsonl", f"analyses/{d}/e39_rows.jsonl"), (HOME / d / "analysis.log", f"analyses/{d}/analysis.log"), (HOME / d / "analysis-c-vs-b.log", f"analyses/{d}/analysis-c-vs-b.log")]
    out += [(f, f"analyses/{f.parent.name}/run.log") for f in sorted(HOME.glob("e35c-heldout-*/run.log"))]
    out += [(f, f"analyses/mrcr-heldout/{f.name}") for f in sorted((HOME / "mrcr-heldout").glob("*.jsonl"))]
    # 24 October: E58 and its secondary arm, stress tests and interface/leaf experiments (rows and analyses, no work dirs)
    for d in ("e58-analysis", "e58a2-analysis"):
        out += [(f, f"analyses/{d}/{f.name}") for f in sorted((HOME / d).glob("*")) if f.is_file()]
    for d, pats in (("e59-stress", ("rows*.jsonl",)), ("e60", ("rows.jsonl", "analysis*.txt")), ("e61", ("*.jsonl",)),
                    ("e68", ("rows.jsonl",)), ("e72", ("rows.jsonl",)), ("e73", ("*.json", "*.txt"))):
        for pat in pats:
            out += [(f, f"analyses/{d}/{f.name}") for f in sorted((HOME / d).glob(pat)) if f.is_file()]
    out += [(f, f"runs-summary/{f.parent.parent.name}/{f.parent.name}.summary.json")
            for run in ("e69-refactor-4brl4", "e69b-refactor-adopt-4brl4", "e69b2-refactor-adopt-4br5b-s16", "e69b8-refactor-adopt-8b")
            for f in sorted((RUNS / run).glob("*/summary.json"))]
    out += [(f, f"analyses/e70-ref/{f.parent.name}.rows.jsonl") for f in
            (RUNS / "e70-oolong-repl-prims-4b" / "rows.jsonl", RUNS / "e70-longbench-repl-prims-4b" / "rows.jsonl") if f.exists()]
    out += [(HOME / "e49-noisy-labels-heldout" / "launch.log", "analyses/e49-noisy-labels/heldout.log"),
            (HOME / "e49-noisy-labels-heldout" / "e49_label_curve.json", "analyses/e49-noisy-labels/e49_label_curve.json")]
    out += [(HOME / "e35c-CALIBRATION.txt", "calibration/e35c-CALIBRATION.txt"),
            (HOME / "e35-boot-8b-oolong-s0" / "CALIBRATION.txt", "calibration/e35-CALIBRATION.txt")]
    return [(s, d) for s, d in out if s.exists()]


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    manifest = []
    for src, rel in sources():
        dst = OUT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        data = dst.read_bytes()
        manifest.append(dict(path=rel, source=str(src.resolve()), bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
    (OUT / "MANIFEST.json").write_text(json.dumps(dict(collected=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                                       files=manifest), indent=1) + "\n")
    (OUT / "README.md").write_text(README)
    print(f"collected {len(manifest)} files, {sum(m['bytes'] for m in manifest) / 1000:.0f} kB into {OUT}")


if __name__ == "__main__":
    main()
